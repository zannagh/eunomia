package de.zannagh.eunomia.ui;

/**
 * A collection of constants for UI sizes so one does not have to memorize them.
 */
public final class UiSizes {

    /**
     * The default spacing between buttons.
     */
    public static final int DEFAULT_BUTTON_SPACING = 8;

    /**
     * The default height of a button on minecraft's UI.
     */
    public static final int DEFAULT_BUTTON_HEIGHT = 20;

    /**
     * The default width of a square button on minecraft's UI.
     */
    public static final int SQUARE_BUTTON_WIDTH = 20;
}
